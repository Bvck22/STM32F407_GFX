"""Generate firmware/Core/Src/sample_data.c from a synthesized phrase or a WAV file."""
from __future__ import annotations

import argparse
import math
import random
import sys
import wave
from pathlib import Path

RATE = 48000
MAX_SECONDS = 8.0  # ~768 KB of int16 flash
PEAK_DBFS = -1.0
FADE_SECONDS = 0.005
DEFAULT_OUT = Path(__file__).resolve().parent.parent / "firmware" / "Core" / "Src" / "sample_data.c"

# Note frequencies (Hz), E minor pentatonic over two octaves.
E2, B2, E3, A2, A3 = 82.41, 123.47, 164.81, 110.00, 220.00
G3, D4, E4, G4, B3, A4 = 196.00, 293.66, 329.63, 392.00, 246.94, 440.00


def pluck(freq: float, seconds: float, rng: random.Random, damping: float = 0.996) -> list[float]:
    """Karplus-Strong string: noise burst in a lowpass-filtered delay line."""
    n = max(2, round(RATE / freq))
    buf = [rng.uniform(-1.0, 1.0) for _ in range(n)]
    # Pre-smooth the burst so the attack is less harsh than raw white noise.
    buf = [(buf[i] + buf[i - 1]) * 0.5 for i in range(n)]
    out = []
    idx = 0
    for _ in range(int(seconds * RATE)):
        nxt = buf[(idx + 1) % n]
        out.append(buf[idx])
        buf[idx] = damping * 0.5 * (buf[idx] + nxt)
        idx = (idx + 1) % n
    return out


def mix_in(mix: list[float], note: list[float], start: float, gain: float) -> None:
    offset = int(start * RATE)
    for i, v in enumerate(note):
        mix[offset + i] += v * gain


def strum(mix: list[float], freqs: list[float], start: float, seconds: float,
          rng: random.Random) -> None:
    for i, f in enumerate(freqs):
        mix_in(mix, pluck(f, seconds, rng, 0.997), start + i * 0.018, 0.8)


def synth_phrase(rng: random.Random) -> list[float]:
    total = 6.0
    mix = [0.0] * int(total * RATE)
    strum(mix, [E2, B2, E3], 0.0, 1.4, rng)
    lick = [E4, G4, A4, G4, E4, D4, B3, G3]
    for i, f in enumerate(lick):
        mix_in(mix, pluck(f, 0.7, rng, 0.9965), 1.6 + i * 0.25, 0.7)
    strum(mix, [A2, E3, A3], 3.9, 1.4, rng)
    strum(mix, [E2, B2, E3], 4.3, 1.4, rng)
    return mix


def normalize(samples: list[float]) -> list[int]:
    peak = max((abs(s) for s in samples), default=0.0)
    if peak == 0.0:
        return [0] * len(samples)
    scale = 32767 * 10 ** (PEAK_DBFS / 20) / peak
    return [max(-32768, min(32767, round(s * scale))) for s in samples]


def fade_edges(samples: list[float]) -> None:
    n = min(int(FADE_SECONDS * RATE), len(samples) // 2)
    for i in range(n):
        g = i / n
        samples[i] *= g
        samples[-1 - i] *= g


def read_wav_mono(path: str) -> tuple[list[float], int]:
    with wave.open(path, "rb") as w:
        channels, width, rate = w.getnchannels(), w.getsampwidth(), w.getframerate()
        raw = w.readframes(w.getnframes())
    if width == 1:
        values = [b - 128 for b in raw]
        full = 128.0
    elif width in (2, 3, 4):
        values = [int.from_bytes(raw[i:i + width], "little", signed=True)
                  for i in range(0, len(raw) - width + 1, width)]
        full = float(1 << (8 * width - 1))
    else:
        raise SystemExit(f"error: unsupported sample width {width * 8} bits")
    frames = len(values) // channels
    mono = [sum(values[f * channels:(f + 1) * channels]) / channels / full for f in range(frames)]
    return mono, rate


def resample(samples: list[float], src_rate: int) -> list[float]:
    if src_rate == RATE or not samples:
        return samples
    step = src_rate / RATE
    count = int((len(samples) - 1) / step) + 1
    out = []
    for i in range(count):
        pos = i * step
        j = int(pos)
        frac = pos - j
        nxt = samples[min(j + 1, len(samples) - 1)]
        out.append(samples[j] * (1 - frac) + nxt * frac)
    return out


def import_wav(path: str, start: float, seconds: float) -> list[float]:
    mono, rate = read_wav_mono(path)
    first = int(start * rate)
    clip = mono[first:first + int(seconds * rate)]
    if not clip:
        raise SystemExit(f"error: --start {start} s is beyond the end of {path}")
    out = resample(clip, rate)
    fade_edges(out)
    return out


def format_c(samples: list[int]) -> str:
    lines = ["/* Generated by tools/make_sample.py — do not edit */",
             '#include "sample_data.h"', "",
             "const int16_t g_sample_data[] = {"]
    for i in range(0, len(samples), 16):
        lines.append("  " + ", ".join(str(s) for s in samples[i:i + 16]) + ",")
    lines += ["};", "",
              f"const uint32_t g_sample_len = {len(samples)}u;",
              f"const uint32_t g_sample_rate = {RATE}u;", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--wav", help="import this WAV instead of synthesizing")
    ap.add_argument("--start", type=float, default=0.0, help="WAV start offset, seconds")
    ap.add_argument("--seconds", type=float, default=6.0, help="WAV length to import (max 8)")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args(argv)

    if args.wav:
        if args.seconds > MAX_SECONDS:
            ap.error(f"--seconds {args.seconds} exceeds the {MAX_SECONDS:g} s flash budget (~768 KB)")
        if args.seconds <= 0 or args.start < 0:
            ap.error("--seconds must be > 0 and --start >= 0")
        samples = import_wav(args.wav, args.start, args.seconds)
    else:
        samples = synth_phrase(random.Random(1234))
    pcm = normalize(samples)
    if len(pcm) > MAX_SECONDS * RATE:
        ap.error(f"sample is {len(pcm) / RATE:.2f} s, over the {MAX_SECONDS:g} s flash budget")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(format_c(pcm), encoding="utf-8", newline="\n")
    peak_db = 20 * math.log10(max(abs(v) for v in pcm) / 32768) if any(pcm) else float("-inf")
    print(f"wrote {args.out}: {len(pcm)} samples, {len(pcm) / RATE:.2f} s, peak {peak_db:.2f} dBFS")
    return 0


if __name__ == "__main__":
    sys.exit(main())
